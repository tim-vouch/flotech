"""Put the care plan PDFs and their terms on the demo care plans page (site/boiler-care-plans/, demo only).

    python3 scripts/care_plan_terms.py      (brochures/single.py runs this after building all three PDFs)

The terms live in one place: PLANS[...]["terms_full"] in brochures/single.py. This script writes them into
"The important details" on the page, one opening section per plan, so the website and the PDFs always match.
It also copies the three PDFs next to the page and adds the download links. Safe to re-run.
The page is demo-only: .github/workflows/pages.yml deletes site/boiler-care-plans before publishing.
"""
import os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "brochures"))
import single  # noqa: E402

PAGE = os.path.join(ROOT, "site", "boiler-care-plans", "index.html")
OUT = os.path.join(ROOT, "brochures", "out")
PLANS = [("priority-homeowner", "Priority Homeowner", "home"),
         ("priority-certificate", "Priority Certificate", "landlord"),
         ("priority-plus", "Priority Plus", "priority")]


def pdf_name(key):
    return "Flotech-Care-Plans-" + "-".join(w.capitalize() for w in key.split("-")) + ".pdf"


def pdf_link(key, name, text=None):
    return (f'<a class="cp-pdf" href="/boiler-care-plans/{pdf_name(key)}" target="_blank" rel="noopener">'
            f'<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" '
            f'stroke-linejoin="round" aria-hidden="true"><path d="M12 4v11m0 0l-4.5-4.5M12 15l4.5-4.5M5 20h14"/></svg>'
            f'{text or f"Download the {name} plan details (PDF)"}</a>')


CSS = """<style>
.cp-pdf{display:inline-flex;align-items:center;gap:7px;margin-top:14px;font-weight:700;font-size:14.5px;color:#7a3fe0;text-decoration:none}
.cp-pdf:hover{text-decoration:underline}
.cp-card .cp-pdf{justify-content:center;width:100%;margin-top:12px;font-size:14px}
.cp-terms .cp-tgrid{columns:2 340px;column-gap:36px}
.cp-terms .cp-tsec{break-inside:avoid;margin-bottom:22px}
.cp-terms .cp-tsec h4{margin:0 0 10px;padding-bottom:7px;border-bottom:1px solid var(--line);color:#7a3fe0}
.cp-terms .cp-tsec p{margin:0 0 10px;font-size:15px;line-height:1.55}
.cp-terms .cp-tsec p b{color:var(--ink,#0A0A0A)}
.cp-terms .cp-tsec a{color:#7a3fe0}
</style>"""


def terms_section():
    blocks = []
    for key, name, tier in PLANS:
        secs = "".join(f'<div class="cp-tsec"><h4>{h}</h4>' + "".join(f"<p><b>{t}.</b> {d}</p>" for t, d in items) + "</div>"
                       for h, items in single.PLANS[key]["terms_full"])
        blocks.append(f'<details class="cp-plan"><summary><span class="cp-tier {tier}">{name}</span><b>Full terms</b></summary>'
                      f'<div class="cp-plan-body"><div class="cp-tgrid">{secs}</div>{pdf_link(key, name)}</div></details>')
    return f"""<section class="cp-sec" id="terms"><!-- generated by scripts/care_plan_terms.py from brochures/single.py: edit the terms there -->
{CSS}
    <div class="cp-wrap">
      <div class="cp-center"><span class="cp-eyebrow">Plan terms</span><h2>The important details</h2>
      <p class="cp-lead">Each plan has its own terms. Tap your plan to read them in full before joining, or download them as a PDF.</p></div>
      <div class="cp-plans-detail cp-terms">{''.join(blocks)}</div>
    </div>
  </section>"""


def main():
    for key, _, _ in PLANS:
        shutil.copyfile(os.path.join(OUT, pdf_name(key)), os.path.join(os.path.dirname(PAGE), pdf_name(key)))
    c = open(PAGE, encoding="utf-8").read()

    # 1. "The important details": rebuilt from the PDF terms
    c, n = re.subn(r'<section class="cp-sec" id="terms">.*?</section>', lambda m: terms_section(), c, count=1, flags=re.S)
    assert n == 1, "terms section not found"

    # 2. a PDF link under each plan card's button, and in each plan's details
    for key, name, _ in PLANS:
        c = re.sub(r'<a class="cp-pdf"[^>]*>(?:(?!</a>).)*?</a><!--card:' + key + '-->', "", c, flags=re.S)
        btn = re.search(r'(<a class="cp-btn [a-z]+" href="#join" data-plan="' + name + r'">[^<]*</a>)', c)
        c = c.replace(btn.group(1), btn.group(1) + pdf_link(key, name, "Plan details (PDF)") + f"<!--card:{key}-->", 1)
        c = re.sub(r'<a class="cp-pdf"[^>]*>(?:(?!</a>).)*?</a><!--details:' + key + '-->', "", c, flags=re.S)
    old = '<p class="cp-small" style="margin-top:12px">See <a href="#terms">The important details</a> for what applies to every plan.</p>'
    new = '<p class="cp-small" style="margin-top:12px">Read the full terms for this plan in <a href="#terms">The important details</a>.</p>'
    c = c.replace(old, new)
    parts = c.split(new)
    if len(parts) == 4:   # one per plan, in page order
        c = parts[0]
        for (key, name, _), rest in zip(PLANS, parts[1:]):
            c += new + pdf_link(key, name) + f"<!--details:{key}-->" + rest
    open(PAGE, "w", encoding="utf-8").write(c)
    print("care plan terms and PDF links written to", os.path.relpath(PAGE, ROOT))


if __name__ == "__main__":
    main()
